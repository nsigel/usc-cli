export type SpriteName = keyof typeof sprites;

// Renders a sprite as an SVG whose pixels are square at any size.
export function spriteSVG(name: SpriteName, scale = 4, label = ""): string {
  const rows = sprites[name];
  const width = Math.max(...rows.map((row) => row.length));
  let rects = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const char = row[x];
      let run = 1;
      while (row[x + run] === char) run++;
      if (char !== "." && palette[char]) {
        rects += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${palette[char]}"/>`;
      }
      x += run;
    }
  });
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${rows.length}" width="${width * scale}" height="${rows.length * scale}" shape-rendering="crispEdges" ${a11y}>${rects}</svg>`;
}
